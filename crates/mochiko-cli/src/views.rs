//! Derived views — the replayed state written back out in the corpus's own file shapes.
//!
//! The log is the source of truth (record D1); a view is a projection of it, regenerated and
//! never hand-edited. Wave 1 emits views only under an explicit `--out`, so no shipped file is
//! written; from wave 6 they relocate repo-side outside `plugins/` (record D9).
//!
//! The views MUST stay human-readable text (record D6): they are the author≠grader read path and
//! the GI-006 reconstruction surface. That is why this module carries a small YAML writer instead
//! of handing a value to a generic serializer — the corpus's shape is block scalars for long
//! text, inline sequences for label and enforces lists, and inline mappings for `when:` terms, and
//! a serializer that quoted every string onto one line would satisfy the parser while destroying
//! the surface the constraint is about.
//!
//! **What a view cannot preserve**, stated rather than glossed:
//!
//! * **Comments.** They do not survive a typed model. The command runtime-kernel header is
//!   regenerated exactly (it is a template over the command's name — verified against all six);
//!   every other comment, including the per-skill headers and the inline `vars` notes, is lost.
//!   The two `enforces: []` reasons are the exception: genesis lifts them into `note:` fields, so
//!   they survive as data.
//! * **Rule field order.** It normalises on emit (P1's A11).
//! * **Scalar style and blank lines.** A string is written in the style this module picks, not
//!   the one the file used.
//!
//! So the view test asserts **semantic** equality through the canonical hash, never bytes.

use crate::model::{DocKind, DocRef, Document};
use crate::replay::State;
use serde_norway::{Mapping, Value};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The column a folded scalar wraps at, counting its indentation.
const WIDTH: usize = 98;

/// The longest item, and the longest whole rendering, an inline sequence may carry before it is
/// written as a block. Keeps `labels:` and `enforces:` on one line the way the corpus writes
/// them, without folding a list of prose strings into an unreadable run.
const INLINE_ITEM_MAX: usize = 60;
const INLINE_TOTAL_MAX: usize = 120;

/// The runtime-kernel header every command schema carries. Verified against all six shipped
/// command schemas: they are this text with the command's own name, and nothing else differs.
const COMMAND_HEADER: &str = "\
# Command content schema for /mochiko:{name}. The command .md instructs a raw, full Read of
# this file at command fire; the model interprets it live — the .md Rules block carries the
# reading grammar. Two semantics live only here:
#   class   floor = non-waivable · must = binding obligation · advisory = guidance, not binding.
#   conditions:  each dimension declares its resolution point (entry-derived · surface-presence ·
#           moment-resolved(<moment>) · user-ruled · standing-trigger); a moment-resolved
#           dimension is unresolved until its named moment — rules gated on it are inapplicable
#           until then.
";

/// What every other kind's view says instead of the comment block it cannot reconstruct.
const DERIVED_HEADER: &str =
    "# Derived view — regenerated by `mochiko-cli views emit` from the migration log. Never \
     hand-edited.\n";

// ---------------------------------------------------------------------------
// paths, headers, documents
// ---------------------------------------------------------------------------

/// Where a document's view sits, relative to the repository root — the path its shipped file
/// occupies today, so a regenerated tree diffs directly against the real one.
pub fn view_path(doc: &DocRef) -> PathBuf {
    match doc.kind {
        DocKind::Skill => PathBuf::from(format!("plugins/mochiko/skills/{}/schema.yaml", doc.name)),
        _ => PathBuf::from(format!("plugins/mochiko/schemas/{}.yaml", doc.name)),
    }
}

/// The comment header a view opens with.
pub fn header(doc: &DocRef) -> String {
    match doc.kind {
        DocKind::Command => COMMAND_HEADER.replace("{name}", &doc.name),
        _ => DERIVED_HEADER.to_string(),
    }
}

/// One document's whole view: its header, then its content.
pub fn render(doc: &DocRef, document: &Document) -> String {
    format!("{}{}", header(doc), to_yaml(&document.to_value()))
}

/// Every document's view, addressed by its repository-relative path, in state order.
pub fn emit(state: &State) -> Vec<(PathBuf, String)> {
    state
        .docs
        .iter()
        .map(|(doc, document)| (view_path(doc), render(doc, document)))
        .collect()
}

/// Write every view under `out`, creating the directories it needs. Returns what it wrote.
///
/// `out` is required by the caller (`views emit --out <dir>` has no default), so this can never
/// overwrite a shipped file by omission.
pub fn emit_to(state: &State, out: &Path) -> std::io::Result<Vec<PathBuf>> {
    let mut written = Vec::new();
    for (relative, text) in emit(state) {
        let path = out.join(relative);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, text)?;
        written.push(path);
    }
    Ok(written)
}

